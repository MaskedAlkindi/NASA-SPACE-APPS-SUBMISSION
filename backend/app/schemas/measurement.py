"""Shared normalised measurement schema used by every module."""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field, field_validator, model_validator

from app.schemas.metrics import METRICS


class DataClass(str, Enum):
    real = "real"            # from a real device / person
    research = "research"    # from a published research dataset
    simulated = "simulated"  # generated by the simulator / synthetic seed


class Quality(str, Enum):
    good = "good"
    fair = "fair"
    poor = "poor"
    unknown = "unknown"


class NormalizedMeasurement(BaseModel):
    astronaut_id: str | None = Field(None, max_length=32, pattern=r"^[A-Za-z0-9_\-]+$")
    metric: str
    value: float | None = None
    value_json: dict[str, Any] | None = None
    unit: str
    timestamp: datetime
    source_device: str = Field("unknown", max_length=120)
    source_module: str = Field(..., max_length=64)
    quality: Quality = Quality.unknown
    data_class: DataClass = DataClass.real
    external_id: str | None = Field(None, max_length=160, description="Source-side ID used for idempotent upserts")

    @field_validator("timestamp")
    @classmethod
    def tz_aware(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            v = v.replace(tzinfo=timezone.utc)
        v = v.astimezone(timezone.utc)
        if v.year < 2000:
            raise ValueError("timestamp out of range")
        return v

    @model_validator(mode="after")
    def check_metric(self):
        mdef = METRICS.get(self.metric)
        if mdef is None:
            raise ValueError(f"unsupported metric '{self.metric}'")
        if self.unit != mdef.unit:
            raise ValueError(f"metric '{self.metric}' must use unit '{mdef.unit}' (got '{self.unit}')")
        if self.value is None and self.value_json is None:
            raise ValueError("value or value_json is required")
        if self.value is not None and not (mdef.min <= self.value <= mdef.max):
            raise ValueError(f"{self.metric} value {self.value} outside plausible range [{mdef.min}, {mdef.max}]")
        if mdef.per_astronaut and not self.astronaut_id:
            raise ValueError(f"metric '{self.metric}' requires astronaut_id")
        if not mdef.per_astronaut:
            self.astronaut_id = None
        return self


class MeasurementOut(BaseModel):
    id: int
    astronaut_id: str | None
    metric: str
    value: float | None
    value_json: dict[str, Any] | None
    unit: str
    timestamp: datetime
    source_device: str
    source_module: str
    quality: str
    data_class: str

    model_config = {"from_attributes": True}


class MeasurementBatch(BaseModel):
    measurements: list[dict[str, Any]] = Field(..., max_length=5000)
    module: str | None = Field(None, description="Ingest through a specific module's adapter (e.g. apple_health)")


class IngestResult(BaseModel):
    accepted: int
    updated: int
    rejected: int
    errors: list[str] = []
    alerts_raised: int = 0
